def dense_to_explicit_csr(X):
    X = np.asarray(X)

    n_rows, n_cols = X.shape
    data = X.ravel()

    indices = np.tile(np.arange(n_cols, dtype=np.int32),n_rows)

    indptr = np.arange(
        0,
        (n_rows + 1) * n_cols,
        n_cols,
        dtype=np.int64)

    return sparse.csr_matrix((data, indices, indptr),shape=X.shape)


