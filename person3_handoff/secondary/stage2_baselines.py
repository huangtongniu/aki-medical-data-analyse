def sha256(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def check(condition, message, checks):
    checks.append({"check": message, "pass": bool(condition)})
    if not condition:
        raise AssertionError(message)


